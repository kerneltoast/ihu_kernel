static int parse_config_file(struct bdaddr_ret *p)
{
	char *data = kmalloc(1000, GFP_KERNEL);
	int ret, flags = O_RDONLY;
        int mac_id = 0;
	int j = 0;
	char *token_m = NULL;
	char *string;

	p->valid = 0;
	if (data && strlen(bdaddr)) {

		snprintf(data, 1000-1, "%s", bdaddr);

		BT_DBG(">+> Mac configuration : '%s'\n", data);

		string = data;
		/* Extract MAC ID byte by byte */
		token_m = strsep(&string, ":");
		while (j < 6 && token_m != NULL) {
			sscanf(token_m, "%x", &mac_id);
			p->dev_addr[j++] = mac_id;
			token_m = strsep(&string, ":");
		}

		BT_DBG(">+> Mac configuration(%d) : '%02x:%02x:%02x:%02x:%02x:%02x'\n",
		       j,
		       p->dev_addr[0],p->dev_addr[1],p->dev_addr[2],
		       p->dev_addr[3],p->dev_addr[4],p->dev_addr[5]);

		if (j != 6)
			return -EINVAL;

		p->valid = 1;
	}

	if (data)
		kfree(data);

	return 0;
}

static int btusb_setup_aptiv(struct hci_dev *hdev)
{
	struct hci_rp_read_local_version *rp;
	struct btusb_data *data = hci_get_drvdata(hdev);
	struct usb_device *udev;
	struct sk_buff *skb;
	u16 bcdDevice, idProduct;
	int _csrpatch = csrpatch;
	csrpatch = 0;
	udev = data->udev;
	bcdDevice = le16_to_cpu(udev->descriptor.bcdDevice);
	idProduct = le16_to_cpu(udev->descriptor.idProduct);

	if (test_bit(HCI_QUIRK_APTIV_USBTIMEOUT, &hdev->quirks)) {
		BT_DBG("Retry setup_aptiv for bcdDevice 0x%x idProduct 0x%x\n", bcdDevice, idProduct);
	} else {
		printk(KERN_EMERG ">+> btusb_setup_aptiv for bcdDevice 0x%x idProduct 0x%x\n", bcdDevice, idProduct);
	}

	BT_DBG("%s", hdev->name);

	if (_csrpatch || idProduct == 1 ) {

		struct bdaddr_ret b;

		parse_config_file(&b);

		BT_DBG(">+> patching CSR firmware\n");
		if (btusb_csr_patch(hdev, &b) == 0) {
		    btusb_csr_warmreset(hdev, 0);
		    set_bit(HCI_QUIRK_APTIV_EXIT, &hdev->quirks);
		}

		return -ENODEV;
	}

	return 0;
}



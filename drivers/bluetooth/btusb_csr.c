static int btusb_csr_warmreset(struct hci_dev *hdev, int m)
{
	/* 00fc13c2 02000900 00000240 00000000 00000000 0000 */
	unsigned char buf[] = { 0xc2,       /* 0: Payload Descriptor: Last Fragment set, First Fragment set, Channel ID = 2 */
				0x02, 0x00, /* 1: Type: SETREQ (0x0002) */
				0x09, 0x00, /* 3: Length in 16-bit integers */
				0x00, 0x00, /* 5: Sequence number */
				0x02, 0x40, /* 7: VarId: 0x4002 */
				0x00, 0x00, /* 9: Status */
				0x00, 0x00, /* 11: fill */
				0x00, 0x00, /* 13: fill */
				0x00, 0x00, /* 15: fill */
				0x00, 0x00  /* 17: fill */
				            /* 19: size */
	};
	struct sk_buff *skb;

	BT_DBG(">+> csr warm_reboot\n");

	atomic_inc(&hdev->cmd_cnt);
	skb = __hci_cmd_sync_ev(hdev, 0xfc00, sizeof(buf), buf, 0, 500);
	if (IS_ERR(skb)) {
		int err = PTR_ERR(skb);
		printk(KERN_EMERG ">+> sending warm_reboot failed, timeout expected (%d)", err);
		return err;
	} else {
		BT_DBG(">+> warm_reboot sent\n");
	}
	kfree_skb(skb);

	/*
	if (m)
		msleep(m);
	*/
	return 0;
}


